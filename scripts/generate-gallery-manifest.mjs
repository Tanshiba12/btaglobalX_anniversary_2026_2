import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";

const root = resolve("public/assets/gallery");
const output = resolve("src/data/gallery.generated.ts");
const imagePattern = /\.(avif|gif|jpe?g|png|webp)$/i;

const toId = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const toPublicPath = (absolutePath) =>
  `/${relative(resolve("public"), absolutePath).split(sep).map(encodeURIComponent).join("/")}`;

const toTitle = (name) =>
  name
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
    .replace(/\b2nd\b/i, "Second")
    .replace(/& Fair Highlights/i, "& Wellness Fair")
    .replace(/\b(At|Of)\b/g, (word, match, offset) => (offset === 0 ? word : word.toLowerCase()))
    .replace(/\bVips\b/g, "VIPs");

function getImageSize(file) {
  const buffer = readFileSync(file);

  if (buffer[0] === 0xff && buffer[1] === 0xd8) {
    let offset = 2;
    while (offset < buffer.length) {
      if (buffer[offset] !== 0xff) {
        offset += 1;
        continue;
      }

      const marker = buffer[offset + 1];
      const length = buffer.readUInt16BE(offset + 2);
      if (marker >= 0xc0 && marker <= 0xc3) {
        return {
          height: buffer.readUInt16BE(offset + 5),
          width: buffer.readUInt16BE(offset + 7)
        };
      }
      offset += 2 + length;
    }
  }

  if (buffer.toString("ascii", 1, 4) === "PNG") {
    return {
      height: buffer.readUInt32BE(20),
      width: buffer.readUInt32BE(16)
    };
  }

  return {};
}

function collectAlbums(directory) {
  const entries = readdirSync(directory, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name, undefined, { numeric: true, sensitivity: "base" })
  );
  const files = entries
    .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
    .map((entry) => resolve(directory, entry.name));
  const childAlbums = entries
    .filter((entry) => entry.isDirectory())
    .flatMap((entry) => collectAlbums(resolve(directory, entry.name)));

  if (!files.length) {
    return childAlbums;
  }

  const folderName = directory.split(sep).at(-1) ?? "Gallery";
  const title = toTitle(folderName);
  const id = toId(relative(root, directory) || folderName);

  return [
    {
      id,
      title,
      images: files.map((file) => {
        const filename = file.split(sep).at(-1) ?? "photo";
        const size = getImageSize(file);
        return {
          alt: `BTA GlobalX ${title} photo`,
          ...size,
          id: `${id}-${toId(filename)}`,
          title: filename.replace(imagePattern, ""),
          src: toPublicPath(file)
        };
      })
    },
    ...childAlbums
  ];
}

const albums = collectAlbums(root);
const content = `// This file is generated by scripts/generate-gallery-manifest.mjs.
// Do not edit manually; add/remove image folders under public/assets/gallery and rerun the generator.
import type { GalleryAlbum } from "./gallery";

export const galleryAlbums: GalleryAlbum[] = ${JSON.stringify(albums, null, 2)};
`;

writeFileSync(output, content);
console.log(`Generated ${albums.length} gallery albums with ${albums.reduce((sum, album) => sum + album.images.length, 0)} images.`);
